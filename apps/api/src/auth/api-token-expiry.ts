/**
 * API 令牌的到期时间口径（纯函数、零依赖 —— 便于单测）。
 *
 * 🔴 这里唯一的坑是「一年」到底按什么算（2026-09-16 线上事故）：
 *
 * 页面上的「到期时间」是 `input[type=date]`，只有**日**精度，提交时取**当天 23:59:59**；
 * 而它的默认值就是「一年后的同一天」。如果服务端上限写成 `now + 365×24h`，
 * 这两个式子会差出几个小时 ——
 *
 *   ```
 *   默认值  2027-09-16 23:59:59（本地）
 *   服务端上限 2027-09-16 21:42:xx（= 此刻 + 365×24h）
 *   ⇒ 默认值 > 上限 ⇒ 「过期时间最长为一年」
 *   ```
 *
 * 结果就是：**用户什么都不改、直接点「确认签发」也会被拒**，整页功能等于不可用。
 *
 * 所以上限按**日历**算：落在「此刻 + 365 天」那一天的 23:59:59.999。
 * 对安全没有实质影响（真正的意图是「不许发十年令牌」，不是卡掉那两小时），
 * 却让「刚好一年」这个唯一的自然表达能够被提交。
 */

/** 一年。用于时间跨度计算，**不要**直接拿它当边界去比 —— 见文件头注释 */
export const MAX_TOKEN_TTL_MS = 365 * 24 * 3600 * 1000;

/**
 * 允许的最晚到期时刻：`now + 365 天` 那一天的 23:59:59.999（**本地时区**）。
 *
 * `setHours` 用的是本地时区，与 `input[type=date]` / `new Date('YYYY-MM-DD')` 的口径一致；
 * 两边必须同口径，否则又会差出一个时区。
 */
export function maxExpiryAt(now: number): number {
  const d = new Date(now + MAX_TOKEN_TTL_MS);
  d.setHours(23, 59, 59, 999);
  return d.getTime();
}
