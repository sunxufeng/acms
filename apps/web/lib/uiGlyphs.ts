/**
 * 界面里的小符号，抽成常量以便「统一」这件事可以被守卫（2026-10-01 超链接方案 B）。
 *
 * 起因：全站「跳转类」按钮的箭头原本硬编码了 3 处 3 种
 * （`查看学生 ↗` / `打开联系人 →` / `打开这条记录 ↗`），改一处风格要全站搜。
 * 现在只留一个来源，并且判据写死成"跨模块/跨页跳转一律用 `JUMP_ARROW`"。
 *
 * ⚠️ 为什么不做进 i18n：箭头是**符号**不是文案，中英一致（`↗` 在两种语言里都表示
 *    "新窗口/外部"）。真正需要翻译的是它旁边的文字（那部分已经走 `t()`）。
 *    ⚠️ 但要注意：**箭头在 JSX 里必须写 `{JUMP_ARROW}`**，不要直接打字符 ——
 *    守卫是按这个标识符找的，直接打字符等于绕过统一。
 */

/**
 * 跨模块 / 跨页跳转（点了会离开当前页面）统一用它。
 *
 * 语义：`↗` = 跳走（新页面 / 别的模块）；`→` = 页内流程的下一步。
 * 两者别混用 —— 混用会让"这个按钮会不会把我带走"变成靠猜。
 */
export const JUMP_ARROW = '↗';

/** 页内流程推进（向导下一步等）用这个，与 `JUMP_ARROW` 区分开 */
export const STEP_ARROW = '→';
