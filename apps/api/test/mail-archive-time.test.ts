import { describe, expect, it } from 'vitest';
import { formatDate, formatDateTime } from '../../web/lib/date.js';

/**
 * 邮件归档「发送时间」只显示到年月日（2026-09-23 峰哥要求）。
 *
 * 🔴 为什么不能简单 `String(v).slice(0, 10)`：库里存的是 **UTC** ISO 串
 * （生产实测：`2025-08-18T09:14:45.000Z`，5557 条都是这个形状；另有 816 条纯日期）。
 * 直接截前 10 位得到的是 **UTC 日期**，东八区晚上发出的邮件会**跨天差一天**
 * —— 例如 `2026-09-08T20:32:41Z` 其实是北京时间 9 月 9 日凌晨 4:32。
 * 所以走 `formatDate`（按浏览器时区换算后再取日期）。
 *
 * ⚠️ 本文件依赖运行环境的时区（CI/开发机为 Asia/Shanghai）。跑测试时若时区不对，
 *    第一条会失败 —— 那说明环境时区非东八区，不是逻辑错了。
 */
describe('formatDate / formatDateTime', () => {
  it('🔴 UTC 串按本地时区换算后再取日期（东八区晚间会落到次日）', () => {
    // 2026-09-08T20:32:41Z = 北京时间 2026-09-09 04:32
    expect(formatDate('2026-09-08T20:32:41.000Z')).toBe('2026-09-09');
    // 而直接截前 10 位会得到 2026-09-08（错一天）—— 这正是要避免的写法
    expect('2026-09-08T20:32:41.000Z'.slice(0, 10)).toBe('2026-09-08');
  });

  it('同一天内的 UTC 串仍取到同一天（不能把正常的也挪走）', () => {
    // 2025-08-18T09:14:45Z = 北京时间 17:14，同日
    expect(formatDate('2025-08-18T09:14:45.000Z')).toBe('2025-08-18');
  });

  it('纯日期串（816 条老数据）不受影响', () => {
    expect(formatDate('2026-09-09')).toBe('2026-09-09');
  });

  it('空值给「—」，解析不了的串原样返回（不吞信息）', () => {
    expect(formatDate('')).toBe('—');
    expect(formatDate(null)).toBe('—');
    expect(formatDate('不是时间')).toBe('不是时间');
  });

  it('formatDateTime 仍然带时分（详情页照常用）', () => {
    expect(formatDateTime('2025-08-18T09:14:45.000Z')).toBe('2025-08-18 17:14');
  });
});
